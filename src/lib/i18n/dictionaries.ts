export type Lang = "en" | "fil";
export const dictionaries: Record<Lang, Dictionary> = { en, fil };

type Join<K, P> = K extends string ? (P extends string ? `${K}.${P}` : never) : never;
type Paths<T> = { [K in keyof T]: T[K] extends string ? K : Join<K, Paths<T[K]>> }[keyof T];
export type TKey = Paths<Dictionary>;

export function translate(dict: Dictionary, key: TKey, vars?: Record<string, string | number>): string {
  let value: unknown = dict;
  for (const part of key.split(".")) value = (value as Record<string, unknown>)?.[part];
  let text = typeof value === "string" ? value : key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
